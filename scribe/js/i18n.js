const CHAR_NAMES_EN = {
  " ": "space",
  "#": "hash",
  "%": "percent",
  "@": "at",
  "©": "copyright",
  "*": "star",
  $: "dollar",
  "★": "star",
};

const CHAR_NAMES_HI = {
  " ": "स्पेस",
  "#": "हैश",
  "%": "प्रतिशत",
  "@": "एट",
  "©": "कॉपीराइट",
  "*": "तारा",
  $: "डॉलर",
  "★": "तारा",
};

export function speakChar(ch, lang = "en") {
  const map = lang === "hi" ? CHAR_NAMES_HI : CHAR_NAMES_EN;
  if (map[ch]) return map[ch];
  if (/[0-9]/.test(ch)) return lang === "hi" ? digitHi(ch) : ch;
  if (/[A-Z]/i.test(ch)) return ch.toUpperCase();
  return ch;
}

function digitHi(ch) {
  return { 0: "शून्य", 1: "एक", 2: "दो", 3: "तीन", 4: "चार", 5: "पाँच", 6: "छह", 7: "सात", 8: "आठ", 9: "नौ" }[ch] || ch;
}

export function t(lang, key, ...args) {
  const bundle = STRINGS[lang] || STRINGS.en;
  const value = bundle[key];
  return typeof value === "function" ? value(...args) : value;
}
